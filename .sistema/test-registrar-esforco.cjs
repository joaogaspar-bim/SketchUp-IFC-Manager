const assert = require('node:assert/strict');
const { normalRepo, caminhos, mesclar, selecionarRepos } = require('./registrar-esforco.cjs');
const { gerar } = require('./atualizar-esforco.cjs');
const id = '36d1a95c-7db6-4f2d-86d2-e5d70fcc6770';
const base = { formato: 'base-esforco-aprovada-v1', projetos: [{ aplicativoId: id, nome: 'SISTEMA EBBIM', corte_em: '2026-11-02T16:05:47.848Z', resumo: { dias_locais: null, primeiro_dia_local: '', ultimo_dia_local: '', horas_5: null, horas_15: null, horas_30: null }, dias: [] }] };
const manifest = { formato: 'andamento-producao-v1', projetos: [{ aplicativoId: id, registros: [{ entidade: 'atividade', chave: 'preservar', dados: { titulo: 'Atividade aprovada' } }] }] };
const record = (key, times) => ({ id: key, aplicativoId: id, atribuicao: 'aplicativo', grupo: 'SISTEMA EBBIM', instantes: times, referencia: '.sistema/esforco-eventos.json#' + key });
const empty = { formato: 'eventos-esforco-v1', registros: [] };
assert.equal(normalRepo('https://inovacao-totalcad@github.com/inovacao-totalcad/Rosaebbim.git'), 'inovacao-totalcad/rosaebbim');
assert.equal(normalRepo('git@github.com:EscolaBrasileiraDeBIM/sistema.git'), 'escolabrasileiradebim/sistema');
assert.deepEqual(caminhos({ code: 'segredo não lido', nested: { workdir: '/trabalho' } }), ['/trabalho']);
assert.equal(selecionarRepos(['a', 'b'], 'a').repo, '');
assert.equal(selecionarRepos(['b'], 'a').repo, 'b');
assert.equal(selecionarRepos([], 'a').repo, 'a');
const r = record('teste', ['2026-11-10T12:00:00Z', '2026-11-10T12:04:00Z']);
assert.deepEqual(mesclar(mesclar(empty, [r]), [r]), mesclar(empty, [r]));
assert.equal(mesclar(mesclar(empty, [r]), [record('teste', [...r.instantes, '2026-11-10T12:08:00Z'])]).registros[0].instantes.length, 3);
assert.throws(() => mesclar(mesclar(empty, [r]), [{ ...r, aplicativoId: 'outro' }]), /Identidade/);
const overlap = mesclar(empty, [r, record('sobreposto', ['2026-11-10T12:02:00Z', '2026-11-10T12:06:00Z'])]);
const output = gerar(base, overlap, manifest);
const effort = output.projetos[0].registros.find(r => r.entidade === 'esforco').dados;
assert.equal(effort.horas_5, 6 / 60);
assert.deepEqual(output.projetos[0].registros[0], manifest.projetos[0].registros[0]);
assert.deepEqual(gerar(base, overlap, output), output);
const midnight = gerar(base, mesclar(empty, [record('meianoite', ['2026-11-10T02:58:00Z', '2026-11-10T03:02:00Z'])]), manifest).projetos[0].registros.find(r => r.entidade === 'esforco').dados;
assert.equal(midnight.dias.length, 2);
assert.equal(midnight.horas_5, 4 / 60);
assert.throws(() => gerar(base, mesclar(empty, [record('passado', ['2026-11-01T12:00:00Z', '2026-11-01T12:01:00Z'])]), manifest), /corte/);
assert.equal(gerar(base, empty, manifest).projetos[0].registros.find(r => r.entidade === 'esforco').dados.horas_15, null);
console.log('15 verificações aprovadas: identidade, atribuição, idempotência, sobreposições, meia-noite, corte e preservação.');
